-- Project: E-commerce Data Platform
-- Version: 1.0
-- Purpose: Operational relational model for a fictional e-commerce business.
-- Target database: PostgreSQL
--
-- Notes:
-- 1. This script creates the schema from scratch. Run it in an empty database.
-- 2. Order totals are derived from order_items and shipping_cost; they are not stored redundantly.
-- 3. Orders preserve a snapshot of the shipping address used at checkout.
-- 4. Status values and numeric boundaries are constrained to protect data quality.

BEGIN;

CREATE TABLE customers (
    customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    phone VARCHAR(30),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    customer_status VARCHAR(20) NOT NULL DEFAULT 'active',
    CONSTRAINT chk_customers_status
        CHECK (customer_status IN ('active', 'inactive'))
);

CREATE TABLE addresses (
    address_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL,
    street VARCHAR(150) NOT NULL,
    street_number VARCHAR(20),
    complement VARCHAR(100),
    neighborhood VARCHAR(100),
    city VARCHAR(100) NOT NULL,
    state VARCHAR(100) NOT NULL,
    postal_code VARCHAR(20) NOT NULL,
    country VARCHAR(100) NOT NULL DEFAULT 'Brazil',
    is_default BOOLEAN NOT NULL DEFAULT FALSE,

    -- Supports a composite FK from orders that validates address ownership.
    CONSTRAINT uq_addresses_address_customer UNIQUE (address_id, customer_id),
    CONSTRAINT fk_addresses_customer
        FOREIGN KEY (customer_id) REFERENCES customers (customer_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT
);

CREATE TABLE categories (
    category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(100) NOT NULL UNIQUE,
    description VARCHAR(500)
);

CREATE TABLE products (
    product_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id INTEGER NOT NULL,
    sku VARCHAR(50) NOT NULL UNIQUE,
    product_name VARCHAR(200) NOT NULL,
    description VARCHAR(1000),
    current_price NUMERIC(12, 2) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_products_current_price CHECK (current_price >= 0),
    CONSTRAINT fk_products_category
        FOREIGN KEY (category_id) REFERENCES categories (category_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT
);

CREATE TABLE orders (
    order_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL,
    shipping_address_id INTEGER NOT NULL,
    order_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    order_status VARCHAR(30) NOT NULL DEFAULT 'pending',
    shipping_cost NUMERIC(12, 2) NOT NULL DEFAULT 0,
    currency_code CHAR(3) NOT NULL DEFAULT 'BRL',

    -- Historical snapshot of the delivery address at checkout.
    shipping_street VARCHAR(150) NOT NULL,
    shipping_street_number VARCHAR(20),
    shipping_complement VARCHAR(100),
    shipping_neighborhood VARCHAR(100),
    shipping_city VARCHAR(100) NOT NULL,
    shipping_state VARCHAR(100) NOT NULL,
    shipping_postal_code VARCHAR(20) NOT NULL,
    shipping_country VARCHAR(100) NOT NULL DEFAULT 'Brazil',

    CONSTRAINT chk_orders_status
        CHECK (order_status IN (
            'pending', 'confirmed', 'processing', 'shipped',
            'delivered', 'cancelled', 'returned'
        )),
    CONSTRAINT chk_orders_shipping_cost CHECK (shipping_cost >= 0),
    CONSTRAINT chk_orders_currency_code CHECK (currency_code ~ '^[A-Z]{3}$'),
    CONSTRAINT fk_orders_customer
        FOREIGN KEY (customer_id) REFERENCES customers (customer_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_orders_address_owner
        FOREIGN KEY (shipping_address_id, customer_id)
        REFERENCES addresses (address_id, customer_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT
);

CREATE TABLE order_items (
    order_item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL,
    product_id INTEGER NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(12, 2) NOT NULL,
    discount_amount NUMERIC(12, 2) NOT NULL DEFAULT 0,

    CONSTRAINT chk_order_items_quantity CHECK (quantity > 0),
    CONSTRAINT chk_order_items_unit_price CHECK (unit_price >= 0),
    CONSTRAINT chk_order_items_discount
        CHECK (discount_amount >= 0 AND discount_amount <= quantity * unit_price),
    CONSTRAINT fk_order_items_order
        FOREIGN KEY (order_id) REFERENCES orders (order_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_order_items_product
        FOREIGN KEY (product_id) REFERENCES products (product_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT uq_order_items_order_product UNIQUE (order_id, product_id)
);

CREATE TABLE payments (
    payment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL,
    payment_date TIMESTAMP,
    payment_method VARCHAR(30) NOT NULL,
    payment_status VARCHAR(30) NOT NULL DEFAULT 'pending',
    amount NUMERIC(12, 2) NOT NULL,
    transaction_reference VARCHAR(100) UNIQUE,

    CONSTRAINT chk_payments_method
        CHECK (payment_method IN ('credit_card', 'debit_card', 'pix', 'boleto', 'wallet')),
    CONSTRAINT chk_payments_status
        CHECK (payment_status IN ('pending', 'approved', 'declined', 'cancelled', 'refunded')),
    CONSTRAINT chk_payments_amount CHECK (amount > 0),
    CONSTRAINT fk_payments_order
        FOREIGN KEY (order_id) REFERENCES orders (order_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT
);

CREATE TABLE shipments (
    shipment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL,
    shipment_status VARCHAR(30) NOT NULL DEFAULT 'pending',
    carrier VARCHAR(100),
    tracking_code VARCHAR(100) UNIQUE,
    shipped_at TIMESTAMP,
    delivered_at TIMESTAMP,

    CONSTRAINT chk_shipments_status
        CHECK (shipment_status IN (
            'pending', 'preparing', 'shipped', 'in_transit',
            'delivered', 'failed', 'returned', 'cancelled'
        )),
    CONSTRAINT chk_shipments_delivery_dates
        CHECK (
            delivered_at IS NULL
            OR (shipped_at IS NOT NULL AND delivered_at >= shipped_at)
        ),
    CONSTRAINT fk_shipments_order
        FOREIGN KEY (order_id) REFERENCES orders (order_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT
);

CREATE TABLE inventory (
    inventory_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER NOT NULL UNIQUE,
    quantity_on_hand INTEGER NOT NULL DEFAULT 0,
    reorder_level INTEGER NOT NULL DEFAULT 0,
    last_updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_inventory_quantity CHECK (quantity_on_hand >= 0),
    CONSTRAINT chk_inventory_reorder_level CHECK (reorder_level >= 0),
    CONSTRAINT fk_inventory_product
        FOREIGN KEY (product_id) REFERENCES products (product_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT
);

-- Helpful indexes for common joins and filters.
CREATE INDEX idx_addresses_customer_id ON addresses (customer_id);
CREATE INDEX idx_products_category_id ON products (category_id);
CREATE INDEX idx_orders_customer_id ON orders (customer_id);
CREATE INDEX idx_orders_order_date ON orders (order_date);
CREATE INDEX idx_orders_status ON orders (order_status);
CREATE INDEX idx_order_items_product_id ON order_items (product_id);
CREATE INDEX idx_payments_order_id ON payments (order_id);
CREATE INDEX idx_shipments_order_id ON shipments (order_id);

-- Table documentation.
COMMENT ON TABLE customers IS 'Customer master data for the fictional e-commerce business.';
COMMENT ON TABLE addresses IS 'Customer delivery addresses; orders also store an address snapshot.';
COMMENT ON TABLE categories IS 'Product categories used to organize the catalog.';
COMMENT ON TABLE products IS 'Product catalog and current sale price.';
COMMENT ON TABLE orders IS 'Order header and delivery-address snapshot. Financial totals are derived from items plus shipping.';
COMMENT ON TABLE order_items IS 'One product line per order, with the sale-time unit price and line-level discount.';
COMMENT ON TABLE payments IS 'Payment attempts and outcomes associated with an order.';
COMMENT ON TABLE shipments IS 'Shipment and delivery tracking records; one order may have multiple shipments.';
COMMENT ON TABLE inventory IS 'Current stock position per product for a single-warehouse scenario.';

COMMIT;
